"""Write a one-bit digital waveform in simple VCD format."""
from __future__ import annotations

from pathlib import Path


def write_vcd(samples: list[int], sample_rate_hz: int, path: str | Path,
              signal_name: str = "uart_rx") -> None:
    if sample_rate_hz <= 0:
        raise ValueError("sample rate must be positive")
    if any(bit not in (0, 1) for bit in samples):
        raise ValueError("VCD values must be 0 or 1")
    p = Path(path)
    with p.open("w", encoding="ascii", newline="\n") as f:
        f.write("$date generated by RP2040 UART Logic Analyzer $end\n")
        f.write("$version rp2040-uart-logic-analyzer host tool $end\n")
        f.write("$timescale 1ns $end\n$scope module capture $end\n")
        f.write(f"$var wire 1 ! {signal_name} $end\n$upscope $end\n$enddefinitions $end\n")
        last = None
        for idx, bit in enumerate(samples):
            # Round to integer nanoseconds; duplicates can occur only at rates > 1 GHz.
            timestamp = round(idx * 1_000_000_000 / sample_rate_hz)
            if bit != last:
                f.write(f"#{timestamp}\n{bit}!\n")
                last = bit
